def main():
    print(f"[*] COU 提取: 网络数据安全风险评估办法")
    print(f"[*] 源文件: {SOURCE_FILE}")
    print(f"[*] 输出目录: {OUTPUT_DIR}")
    print(f"[*] 基础权重: {BASE_WEIGHT} (部门规章层级)")
    print()

    stats = {"total": 0, "应当": 0, "不得": 0, "可以": 0, "鼓励": 0, "其他": 0}
    articles_seen = set()

    used_ids = {}
    for (article, sub_clause, subject, action, obj, condition, domain, factor, original) in COU_DEFINITIONS:
        base = f"COU-R-{COU_PREFIX}-{article.replace('条','')}"
        # 用子句标记作为唯一后缀
        if sub_clause:
            suffix = sub_clause.replace(" ", "-").replace("—", "-")
            cou_id = f"{base}-{suffix}"
        else:
            cou_id = base
        # 简并
        cou_id = cou_id.replace("--", "-")
        # 确保唯一
        if cou_id in used_ids:
            used_ids[cou_id] += 1
            cou_id = f"{cou_id}-{used_ids[cou_id]}"
        else:
            used_ids[cou_id] = 0

        cid, fp, fw = write_cou(cou_id, article, sub_clause, subject, action, obj, condition, domain, factor, original)
        articles_seen.add(article)
        stats["total"] += 1
        if action in stats:
            stats[action] += 1
        else:
            stats["其他"] += 1
        print(f"  [COU] {cid:45s} | w={fw:5.1f} | {fp[:50]}...")

    print()
    print(f"========== 提取完成 ==========")
    print(f"  总 COU 数: {stats['total']}")
    print(f"  涉及条款: {len(articles_seen)} 条")
    print(f"  应当: {stats.get('应当', 0)} | 不得: {stats.get('不得', 0)} | 可以: {stats.get('可以', 0)} | 鼓励: {stats.get('鼓励', 0)} | 其他: {stats['其他']}")
    print(f"  输出目录: {OUTPUT_DIR}")


if __name__ == "__main__":
    main()
